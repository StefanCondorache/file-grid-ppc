// Generates TS types from the OpenAPI proposal and a JSON copy for the MSW baseline.
// API_SPEC overrides the source (later: the backend's /api/docs-json).
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';
import { parse } from 'yaml';

const root = new URL('../', import.meta.url);
const spec = process.env.API_SPEC ?? fileURLToPath(new URL('../docs/api/openapi.frontend-proposal.yaml', root));
const isUrl = /^https?:/.test(spec);

const doc = isUrl ? await (await fetch(spec)).json() : parse(readFileSync(spec, 'utf8'));
const ast = await openapiTS(doc);
writeFileSync(new URL('src/lib/api/schema.d.ts', root), `// Generated by scripts/gen-api.mjs. Do not edit.\n${astToString(ast)}`);
mkdirSync(new URL('src/mocks/', root), { recursive: true });
writeFileSync(new URL('src/mocks/openapi.json', root), JSON.stringify(doc, null, 2) + '\n');
console.log(`types + openapi.json generated from ${spec}`);
